"""Generate local/theme/mapShape.ts: the land outline (minus lakes) and the Canada/US border
for the "based in" card, from Natural Earth 1:50m data (public domain).

Run (needs the three GeoJSON files from natural-earth-vector at the pinned commit):
  uv run --no-project --with shapely==2.1.2 python local/tools/gen_map.py <dir-with-geojson> <commit-sha>

The output is committed, so the site build never touches the network.
"""
import json
import math
import sys
from pathlib import Path

from shapely.geometry import box, mapping, shape
from shapely.ops import transform, unary_union

SRC, SHA = Path(sys.argv[1]), sys.argv[2]
OUT = Path(__file__).resolve().parents[1] / "theme" / "mapShape.ts"

# Great Lakes region framed around Toronto. Equirectangular, x scaled by cos(mid-latitude).
LON0, LON1, LAT0, LAT1 = -95.0, -63.5, 38.5, 52.0
PIN = {"name": "Toronto", "lon": -79.38, "lat": 43.65}
W = 400.0
K = math.cos(math.radians((LAT0 + LAT1) / 2))
H = round(W * (LAT1 - LAT0) / ((LON1 - LON0) * K), 1)


def project(lon, lat):
    x = (lon - LON0) / (LON1 - LON0) * W
    y = (LAT1 - lat) / (LAT1 - LAT0) * H
    return x, y


def load(name):
    data = json.loads((SRC / f"{name}.geojson").read_text(encoding="utf-8"))
    return [shape(f["geometry"]) for f in data["features"]]


frame = box(LON0 - 1, LAT0 - 1, LON1 + 1, LAT1 + 1)
land = unary_union([g.intersection(frame) for g in load("ne_50m_land") if g.intersects(frame)])
lakes = unary_union([g.intersection(frame) for g in load("ne_50m_lakes") if g.intersects(frame)])
area = land.difference(lakes)
border = unary_union([g.intersection(frame) for g in load("ne_50m_admin_0_boundary_lines_land") if g.intersects(frame)])

proj = lambda g: transform(lambda x, y, z=None: project(x, y), g).simplify(0.6, preserve_topology=True)
area, border = proj(area), proj(border)


def ring_d(coords):
    pts = [f"{x:.1f} {y:.1f}" for x, y in coords]
    return "M" + "L".join(pts) + "Z"


def poly_d(g):
    polys = [g] if g.geom_type == "Polygon" else list(g.geoms)
    out = []
    for p in polys:
        if p.area < 2:  # drop specks smaller than a dot
            continue
        out.append(ring_d(p.exterior.coords))
        out.extend(ring_d(r.coords) for r in p.interiors if abs(r.envelope.area) >= 2)
    return "".join(out)


def line_d(g):
    lines = [g] if g.geom_type == "LineString" else [l for l in getattr(g, "geoms", []) if l.geom_type == "LineString"]
    return "".join("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in l.coords) for l in lines)


px, py = project(PIN["lon"], PIN["lat"])
land_d, border_d = poly_d(area), line_d(border)
OUT.write_text(
    f"""// GENERATED by local/tools/gen_map.py. Do not edit by hand.
// Source: Natural Earth 1:50m land, lakes and land boundaries (public domain),
// github.com/nvkelso/natural-earth-vector@{SHA}
// Frame: lon {LON0}..{LON1}, lat {LAT0}..{LAT1}, equirectangular (x scaled by cos {math.degrees(math.acos(K)):.2f}°).
export const MAP_VIEWBOX = '0 0 {W:g} {H:g}';
export const MAP_LAND = '{land_d}';
export const MAP_BORDER = '{border_d}';
export const MAP_PIN = {{ name: '{PIN["name"]}', x: {px:.1f}, y: {py:.1f} }};
""",
    encoding="utf-8",
    newline="\n",
)
print(f"wrote {OUT} viewBox 0 0 {W:g} {H:g}, land {len(land_d)} chars, border {len(border_d)} chars, pin ({px:.1f}, {py:.1f})")
